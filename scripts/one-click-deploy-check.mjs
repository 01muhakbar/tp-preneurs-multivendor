import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const failures = [];
const warnings = [];

const requireFile = (file) => {
  if (!fs.existsSync(path.join(root, file))) {
    failures.push(`Missing required deploy file: ${file}`);
  }
};

const requireText = (file, pattern, message) => {
  const content = read(file);
  const ok = pattern instanceof RegExp ? pattern.test(content) : content.includes(pattern);
  if (!ok) failures.push(`${file}: ${message}`);
};

const getTrackedRuntimeArtifacts = () => {
  const result = spawnSync(
    "git",
    [
      "ls-files",
      "--",
      "cookies*.txt",
      "tmp_*",
      "tmp-*",
      "uploads",
      "server/uploads",
      "server/server/uploads",
      "server/public/uploads/products/product-*",
    ],
    {
      cwd: root,
      encoding: "utf8",
    }
  );

  if (result.status !== 0) {
    warnings.push("Could not inspect tracked runtime artifacts with git ls-files.");
    return [];
  }

  return result.stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
};

[
  "Dockerfile",
  ".dockerignore",
  ".gitignore",
  "render.yaml",
  ".github/workflows/deploy-readiness.yml",
  "docs/render-tidb-deployment.md",
  "docs/production-deployment-checklist.md",
  "server/src/config/deploymentOrigin.ts",
].forEach(requireFile);

requireText("render.yaml", /runtime:\s*docker/, "Render service must use Docker runtime.");
requireText("render.yaml", /dockerCommand:\s*pnpm deploy:start/, "Render service must use the deploy start script.");
requireText("render.yaml", /healthCheckPath:\s*\/api\/health/, "Render health check must point to /api/health.");
requireText("render.yaml", /autoDeployTrigger:\s*checksPass/, "Auto-deploy should wait for CI checks.");
requireText("render.yaml", /preDeployCommand:\s*pnpm deploy:pre/, "Pre-deploy command must run migrations through the repo script.");
requireText("render.yaml", /key:\s*DATABASE_URL[\s\S]*sync:\s*false/, "DATABASE_URL must be prompted, not committed.");
requireText("render.yaml", /key:\s*JWT_SECRET[\s\S]*generateValue:\s*true/, "JWT_SECRET should be generated by Render.");

requireText("Dockerfile", "COPY --from=build /app/client/dist ./client/dist", "Client dist must be copied into the runtime image.");
requireText("Dockerfile", "COPY --from=build /app/server/dist ./server/dist", "Server dist must be copied into the runtime image.");
requireText("Dockerfile", "COPY --from=build /app/server/migrations ./server/migrations", "Migrations must be available to pre-deploy.");
requireText("Dockerfile", "COPY --from=build /app/server/public ./server/public", "Intentional public demo assets must be available in production.");

const pkg = JSON.parse(read("package.json"));
for (const script of ["build", "start", "deploy:pre", "deploy:start", "deploy:verify"]) {
  if (!pkg.scripts?.[script]) failures.push(`package.json: missing script "${script}".`);
}

const trackedRuntimeArtifacts = getTrackedRuntimeArtifacts();
if (trackedRuntimeArtifacts.length > 0) {
  failures.push(
    [
      "Runtime artifacts are still tracked by git:",
      ...trackedRuntimeArtifacts.map((item) => `  - ${item}`),
    ].join("\n")
  );
}

if (warnings.length > 0) {
  warnings.forEach((warning) => console.warn(`[one-click-deploy-check][warning] ${warning}`));
}

if (failures.length > 0) {
  console.error("[one-click-deploy-check] Failed:");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}

console.log("[one-click-deploy-check] OK: Render Blueprint, Docker image, scripts, and tracked artifacts are deploy-ready.");
